"""Writes the paper's data-driven TikZ figures from results/*.json (and the work folder's pca.json, which may hold the author's point)."""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); RES = os.path.join(HERE, "..", "results"); OUT = os.path.join(HERE, "..", "paper", "figures")
W = sys.argv[1] if len(sys.argv) > 1 else RES
cap = json.load(open(os.path.join(RES, "capalibag.json"))); close = json.load(open(os.path.join(RES, "closeness.json")))
pca = json.load(open(os.path.join(W, "pca.json")))
tex = lambda s: s.replace("&", "\\&").replace("%", "\\%")

# regions: stacked bars, Byzantine / Çapalıbağ / Kartvelian
L = ["% Generated by analysis/10_paper_figures.py from results/capalibag.json.", "\\begin{tikzpicture}[x=0.5mm, y=-4.2mm, font=\\scriptsize]"]
for i, r in enumerate(cap):
    name = {"North Anatolia (western Black Sea)": "North (W. Black Sea)", "South (Adana, Mersin, Gaziantep)": "South", "Trabzon, Rize, Artvin": "Trabzon, Rize, Artvin", "Azerbaijani": "Azerbaijanis"}.get(r["cluster"], r["cluster"])
    L.append(f"  \\node[anchor=east{', font=\\scriptsize\\bfseries' if i == 0 else ''}] at (-2,{i}) {{{tex(name)}}};")
    x = 0
    for k, col, pat in (("byz", "tkblue!60", ""), ("cap", "tkorange!75", ""), ("kar", "tkgreen!55", ", pattern=north east lines, pattern color=tkgreen")):
        v = r[k]
        if v > 0:
            L.append(f"  \\fill[{col}{pat}] ({x:.1f},{i}-0.38) rectangle ({x+v:.1f},{i}+0.38);")
            if v >= 9: L.append(f"  \\node[font=\\tiny{', fill=white, inner sep=0.5pt' if k == 'kar' else ''}] at ({x+v/2:.1f},{i}) {{{v:.0f}}};")
        x += v
    L.append(f"  \\draw[tkink, line width=0.3pt] (0,{i}-0.38) rectangle (100,{i}+0.38);")
    L.append(f"  \\node[anchor=west, font=\\tiny] at (101,{i}) {{{r['fit']:.2f}}};")
L += ["  \\node[anchor=west, font=\\tiny] at (101,-0.9) {fit};", "\\end{tikzpicture}"]
open(os.path.join(OUT, "regions.tex"), "w").write("\n".join(L) + "\n")

# closeness: horizontal bars
COL = {"oghuz": "tkorange", "tr": "tkorange!50", "wa": "tkgreen", "cauc": "tkgreen", "eu": "tkblue", "kipchak": "tkink!45", "turkic": "tkink!45"}
L = ["% Generated by analysis/10_paper_figures.py from results/closeness.json.", "\\begin{tikzpicture}[x=1.15mm, y=-3.1mm, font=\\scriptsize]"]
for t in (0, 10, 20, 30):
    L.append(f"  \\draw[tkink!25] ({t},-0.7) -- ({t},{len(close)-0.3}); \\node[font=\\tiny] at ({t},-1.2) {{{t}}};")
for i, r in enumerate(close):
    lab = r["label"].replace("Kurds · west & Alevi (Malatya, Kayseri, Çorum, Maraş)", "Kurds · west \\& Alevi").replace(" · ", ", ")
    L.append(f"  \\node[anchor=east, font=\\tiny] at (-0.5,{i}) {{{tex(lab) if '\\&' not in lab else lab}}};")
    L.append(f"  \\fill[{COL[r['kind']]}] (0,{i}-0.32) rectangle ({min(r['d'], 36):.2f},{i}+0.32);")
    L.append(f"  \\node[anchor=west, font=\\tiny] at ({min(r['d'], 36):.2f},{i}) {{{r['d']:.1f}}};")
L += ["\\end{tikzpicture}"]
open(os.path.join(OUT, "closeness.tex"), "w").write("\n".join(L) + "\n")

# PCA: same label slots as the website figure (pixel slots of a 480 x 340 px frame), with leader lines
X0, X1, Y0, Y1 = -0.09, 0.26, -0.065, 0.095
FW, FH = 140, 62  # frame in mm
P = lambda x, y: ((min(x, X1) - X0) / (X1 - X0) * FW, (y - Y0) / (Y1 - Y0) * FH)
PX = lambda sx, sy: ((sx - 170) / 480 * FW, (380 - sy) / 340 * FH)
COLP = {"tr": "tkorange", "oghuz": "tkorange!60!black", "kipchak": "tkink!50", "turkic": "tkink!50", "wa": "tkgreen", "cauc": "tkgreen!70!black", "eu": "tkblue", "anc": "black"}
SLOT = {"Bulgarian": (258, 64, "west"), "Gagauz": (258, 88, "west"), "Turkish · Balkans": (289, 113, "west"), "Greek · mainland & islands": (200, 112, "east"),
        "Italian · South": (200, 136, "east"), "Crimean Tatar": (445, 167, "west"), "Byzantine Anatolia": (190, 182, "east"), "Bronze Age Anatolia": (176, 210, "east"),
        "Greek · Anatolia & Pontus": (196, 244, "east"), "Çapalıbağ (1300–1650)": (374, 214, "west"), "Turkish · core Anatolia": (322, 254, "west"),
        "Medieval Turkic": (622, 220, "east"), "Uzbek": (582, 278, "north"), "Turkmen": (445, 292, "west"), "Kazakh": (700, 222, "east"), "Kyrgyz": (700, 256, "east"),
        "Armenian": (196, 278, "east"), "Turkish · Erzurum & east": (196, 298, "east"), "Turkish · Trabzon & Rize": (196, 318, "east"), "Georgian & Laz": (200, 366, "east"),
        "Azerbaijani": (340, 300, "west"), "North Caucasus": (340, 317, "west"), "Kurds · west & Alevi (Malatya, Kayseri, Çorum, Maraş)": (340, 334, "west"),
        "Kurds · southeast, Iraq & Iran": (340, 351, "west"), "Persian": (340, 368, "west")}
SHORT = {"Kurds · west & Alevi (Malatya, Kayseri, Çorum, Maraş)": "Kurds, west and Alevi", "Kurds · southeast, Iraq & Iran": "Kurds, southeast, Iraq, Iran"}
L = ["% Generated by analysis/10_paper_figures.py from the PCA output (07_pca.py).", "\\begin{tikzpicture}[x=1mm, y=1mm, font=\\tiny]", f"  \\draw[tkink!40] (0,0) rectangle ({FW},{FH});",
     f"  \\node[anchor=north east] at ({FW},-1) {{PC1 ({pca['explained'][0]}\\%) $\\rightarrow$ toward the Central Asian steppe}};", f"  \\node[anchor=south west] at (0,{FH+1}) {{PC2 ({pca['explained'][1]}\\%) $\\uparrow$ toward Europe}};"]
for g in pca["groups"]:
    for q in g["pts"]:
        if q[0] <= X1:
            x, y = P(*q); L.append(f"  \\fill[{COLP[g['kind']]}, opacity=0.25] ({x:.1f},{y:.1f}) circle (0.4);")
for g in pca["groups"]:
    x, y = P(*g["c"]); off = g["c"][0] > X1
    sx, sy, anc = SLOT[g["label"]]; lx, ly = PX(sx, sy)
    L.append(f"  \\draw[tkink!50, line width=0.25pt] ({x:.1f},{y:.1f}) -- ({lx:.1f},{ly:.1f});")
    if g["kind"] == "anc": L.append(f"  \\draw[black, fill=white, thick] ({x:.1f},{y:.1f}) +(-1,0) -- +(0,1) -- +(1,0) -- +(0,-1) -- cycle;")
    elif off: L.append(f"  \\fill[{COLP[g['kind']]}] ({x-1.4:.1f},{y+1:.1f}) -- ({x:.1f},{y:.1f}) -- ({x-1.4:.1f},{y-1:.1f}) -- cycle;")
    else: L.append(f"  \\fill[{COLP[g['kind']]}] ({x:.1f},{y:.1f}) circle (0.9);")
    bold = ", font=\\tiny\\bfseries" if g["kind"] in ("tr", "anc") else ""
    L.append(f"  \\node[anchor={anc}, inner sep=0.6pt, fill=white, fill opacity=0.8, text opacity=1{bold}] at ({lx:.1f},{ly:.1f}) {{{tex(SHORT.get(g['label'], g['label']).replace(' · ', ', '))}}};")
if pca.get("you"):
    x, y = P(*pca["you"]); L.append(f"  \\draw[black, very thick, fill=white] ({x:.1f},{y:.1f}) circle (1.1); \\node[above=1.3mm, font=\\tiny\\bfseries, fill=white, inner sep=0.5pt] at ({x:.1f},{y:.1f}) {{author}};")
L.append("\\end{tikzpicture}")
open(os.path.join(OUT, "pca.tex"), "w").write("\n".join(L) + "\n")
print("wrote regions.tex closeness.tex pca.tex")
